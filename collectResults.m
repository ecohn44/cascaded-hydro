%% ========================================================================
% SWEEP COLLECTION
% ========================================================================

function T = collectResults(tag)
% Build summary and paired tables from a runSweep folder
%
% Inputs:
%   tag  - the sweep tag, as passed to runSweep
%
% Outputs:
%   T    - the summary table, one row per run
%
% Usage:
%   T = collectResults('N720_grid');
%
% Writes results/runs/<tag>/summary_<tag>.csv (one row per run)
% and paired_<tag>.csv (SSH vs BON and DDU vs DIU per scenario/eps/kappa).

%% 1. Locate the sweep and load the case
root=fileparts(mfilename('fullpath'));
addpath(root); addpath(fullfile(root,'functions'));
outDir=fullfile(root,'results','runs',tag);
d=dir(fullfile(outDir,'jobs','*.mat'));
C=dataload(root,2024,0.20,7);
% The job files do not record Theta, SigmaModel or the kappa knobs, so read
% them from the sweep config beside them. Without this, summaries from a
% theta sweep are distinguishable only by folder name and cannot be safely
% concatenated. NaN/"" if the config is missing (very old tags).
SW=struct();
cfgFile=fullfile(outDir,'sweep_config.mat');
if isfile(cfgFile), Z=load(cfgFile,'cfg'); SW=Z.cfg; end
swTheta   = getfield_or(SW,'Theta',NaN);
swSigma   = string(getfield_or(SW,'SigmaModel',""));
swPolK    = getfield_or(SW,'PolicyKappa',NaN);
swWorldK  = getfield_or(SW,'WorldKappa',NaN);
swFloor   = getfield_or(SW,'FloorPct',NaN);
swTrack   = string(getfield_or(SW,'TrackSide',""));
swPower   = string(getfield_or(SW,'PowerModel',""));
swPFlat   = getfield_or(SW,'PriceFlatten',NaN);
%% 2. One row per finished job
rows=[];
for q=1:numel(d)
    S=load(fullfile(d(q).folder,d(q).name),'summary','small','job');
    sm=S.summary; sl=S.small; jb=S.job;
    dV=sl.V(end,:)-sl.V0;
    % SSH-side feasibility diagnostics are only computed when SSH actually
    % solves. In a BON run SSHStepFeasible and SSHFirstFeasible keep their
    % initialised value of true and ProbeSshObj stays NaN, so six columns
    % would report numbers that look meaningful and are not:
    %   probe_ssh_infeas, probe_ssh_only, probe_contain_viol,
    %   probe_obj_worse, first_ssh_infeas, first_ssh_only
    % Report NaN for those on BON rows. Quote them from SSH rows only.
    isSSH = strcmpi(string(jb.method),"SSH");
    r=struct('scen',jb.scen,'eps',jb.eps,'policy',string(jb.policy), ...
        'kappa',jb.kappa,'method',string(jb.method),'hours',sm.hours, ...
        'energy_MWh',sm.energy_MWh, ...
        'energy_adj_MWh',sm.energy_MWh+water_value(sl.head,C)*dV(:), ...
        'dStorage_kaf',sum(dV),'lower_exit_pct',sm.lower_exit_pct, ...
        'lower_ivi_kaf',sm.lower_ivi_kaf,'spill_kaf',sm.spill_kaf, ...
        'curtail_MWh',sm.curtail_MWh,'track_err',sm.mean_track_error, ...
        'below_eps_hrs',sm.joint_target_violation_hours, ...
        'rel_mean',sm.joint_reliability_mean, ...
        'step_infeas',sm.chance_infeasible_steps, ...
        'planned_slack_kaf',getfield_or(sm,'planned_storage_slack_kaf',NaN), ...
        'planned_slack_hrs_pct',getfield_or(sm,'planned_slack_hours_pct',NaN), ...
        'probe_bon_infeas',sm.probe_bon_infeasible_steps, ...
        'probe_ssh_infeas',ssh_only_field(isSSH,sm.probe_ssh_infeasible_steps), ...
        'probe_ssh_only',ssh_only_field(isSSH,sm.probe_ssh_only_feasible_steps), ...
        'probe_contain_viol',ssh_only_field(isSSH,sm.probe_containment_violations), ...
        'probe_obj_worse',ssh_only_field(isSSH,sm.probe_obj_worse_steps), ...
        'probe_obj_gain_pct',sm.probe_obj_gain_pct_mean, ...
        'first_bon_infeas',sm.first_bon_infeasible_hours, ...
        'first_ssh_infeas',ssh_only_field(isSSH,sm.first_ssh_infeasible_hours), ...
        'first_ssh_only',ssh_only_field(isSSH,sm.first_ssh_only_feasible_hours), ...
        'guard',sm.ssh_guard_steps,'fallback',sm.ssh_slater_fallback_hours, ...
        'emergency',sm.emergency_solve_hours, ...
        'solve_mean_s',sm.solve_time_mean_s,'solve_p95_s',sm.solve_time_p95_s, ...
        'mc_gap_MW',getfield_or(sm,'mc_gap_mean_MW',NaN), ...
        'revenue_usd',getfield_or(sm,'revenue_usd',NaN), ...
        'revenue_sched_usd',getfield_or(sm,'revenue_sched_usd',NaN), ...
        'price_noise_sigma',getfield_or(sm,'price_noise_sigma',0), ...
        'price_mode',string(getfield_or(sm,'price_mode','')), ...
        'price_mean',getfield_or(sm,'price_mean_usd_per_mwh',NaN), ...
        'theta',swTheta,'sigma_model',swSigma,'policy_kappa',swPolK, ...
        'world_kappa',swWorldK,'floor_pct',swFloor,'track_side',swTrack, ...
        'power_model',swPower,'price_flatten',swPFlat);
    rows=[rows; r]; %#ok<AGROW>
end
%% 3. Summary table
T=struct2table(rows);
T=sortrows(T,{'scen','eps','policy','kappa','method'});
writetable(T,fullfile(outDir,['summary_' tag '.csv']));

% ---- paired tables
%% 4. Paired table: SSH vs BON and DDU vs DIU
P=[];
keys=unique(T(:,{'scen','eps','policy','kappa'}),'rows');
for q=1:height(keys)
    k=keys(q,:);
    sel=T.scen==k.scen & T.eps==k.eps & T.policy==k.policy & T.kappa==k.kappa;
    b=T(sel & T.method=="BON",:); s=T(sel & T.method=="SSH",:);
    if isempty(b) || isempty(s), continue, end
    d=find(T.scen==k.scen & T.eps==k.eps & T.policy=="DIU");
    dB=T(intersect(d,find(T.method=="BON")),:); dS=T(intersect(d,find(T.method=="SSH")),:);
    % A missing or errored DIU reference row used to throw here and kill the
    % whole paired table; skip that cell instead.
    if height(dB)~=1 || height(dS)~=1, continue, end
    r=struct('scen',k.scen,'eps',k.eps,'policy',k.policy,'kappa',k.kappa, ...
        'ssh_vs_bon_energy_pct',100*(s.energy_MWh/b.energy_MWh-1), ...
        'ssh_vs_bon_energy_adj_pct',100*(s.energy_adj_MWh/b.energy_adj_MWh-1), ...
        'ssh_vs_bon_ivi_kaf',s.lower_ivi_kaf-b.lower_ivi_kaf, ...
        'ssh_vs_bon_exit_pts',s.lower_exit_pct-b.lower_exit_pct, ...
        'below_eps_bon',b.below_eps_hrs,'below_eps_ssh',s.below_eps_hrs, ...
        'ssh_only_steps',s.probe_ssh_only,'bon_infeas_steps',s.probe_bon_infeas, ...
        'ssh_infeas_steps',s.probe_ssh_infeas,'ssh_only_first',s.first_ssh_only, ...
        'obj_gain_pct',s.probe_obj_gain_pct, ...
        'ddu_vs_diu_energy_pct_bon',100*(b.energy_MWh/dB.energy_MWh-1), ...
        'ddu_vs_diu_energy_pct_ssh',100*(s.energy_MWh/dS.energy_MWh-1), ...
        'ddu_vs_diu_energy_adj_pct_bon',100*(b.energy_adj_MWh/dB.energy_adj_MWh-1), ...
        'ddu_vs_diu_energy_adj_pct_ssh',100*(s.energy_adj_MWh/dS.energy_adj_MWh-1), ...
        'ddu_ivi_reduction_pct_bon',100*(1-b.lower_ivi_kaf/max(dB.lower_ivi_kaf,1e-9)), ...
        'ddu_ivi_reduction_pct_ssh',100*(1-s.lower_ivi_kaf/max(dS.lower_ivi_kaf,1e-9)));
    P=[P; r]; %#ok<AGROW>
end
if ~isempty(P)
    P=struct2table(P);
    writetable(P,fullfile(outDir,['paired_' tag '.csv']));
    fprintf('\n=== %s: %d runs, %d pairs. Validity: containment viol %d, dominance worse %d, guard %d, fallback hrs %d, failures %d ===\n', ...
        tag,height(T),height(P),sum(T.probe_contain_viol(T.method=="SSH")), ...
        sum(T.probe_obj_worse(T.method=="SSH")),sum(T.guard(T.method=="SSH")), ...
        sum(T.fallback(T.method=="SSH")),numel(dir(fullfile(outDir,'jobs','*_error.txt'))));
    G=groupsummary(P,{'eps','policy','kappa'},'mean', ...
        {'ssh_only_steps','ssh_only_first','obj_gain_pct','ssh_vs_bon_energy_pct', ...
        'ssh_vs_bon_energy_adj_pct','below_eps_bon','below_eps_ssh'});
    disp(G);
end
end

function w=water_value(head,C)
n=numel(C.units); mwhPerKaf=C.CPOW*head/C.KAF; w=zeros(1,n);
for i=1:n
    d=i;
    while d>0
        w(i)=w(i)+mwhPerKaf(d);
        d=find(C.upstream==d,1); if isempty(d), d=0; end
    end
end
end


function v=getfield_or(s,f,d)
if isfield(s,f), v=s.(f); else, v=d; end
end

function v=ssh_only_field(isSSH,val)
% NaN unless SSH actually ran, so the column cannot mislead
if isSSH, v=val; else, v=NaN; end
end
